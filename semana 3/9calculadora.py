# Solicita al usuario:
# •	Ingrese Primer número a 
# •	Ingrese Segundo número b

# Calcula y muestra:
# •	Suma : x
# •	Resta : y
# •	Multiplicación : z
# •	División : zz

a = float(input("Ingrese el valor de Primer numero: "))
b = float(input("Ingrese el valor de Segundo numero: "))

print("Suma: ", a + b)
print("resta: ", a - b)
print("Multi: ", a * b)
print("Division: ", a / b)
